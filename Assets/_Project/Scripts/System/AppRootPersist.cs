using UnityEngine;

public sealed class AppRootPersist : MonoBehaviour
{
    private static AppRootPersist _instance;

    private void Awake()
    {
        if (_instance != null && _instance != this)
        {
            Destroy(gameObject);
        }
        else
        {
            _instance = this;
            DontDestroyOnLoad(gameObject);
        }
    }
}